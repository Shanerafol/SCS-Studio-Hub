app.post('/api/receipts', wrap((req, res) => {

  const { orderId, paymentMethod, otherPayment, items, discount = 0, customerName = '', customerAddress = '', customerContact = '', receiptDate } = req.body;

  if (!['Cash', 'GCash', 'Bank Transfer', 'Others', 'Not specified'].includes(paymentMethod))
    throw Error('Choose a payment method');

  const order = orderId ? db.orders.find(o => o.id === Number(orderId)) : null;

  if (orderId && !order)
    throw Error('Order not found');

  const usedItems = order ? order.items.map(i => ({ name: db.products.find(p => p.id === i.productId)?.name || 'Product', qty: i.quantity, price: i.unitPrice })) : items;

  if (!Array.isArray(usedItems) || !usedItems.length)
    throw Error('Add at least one item');

  if (usedItems.some(i => !String(i.name || '').trim() || !Number.isFinite(Number(i.price)) || Number(i.price) < 0 || !Number.isInteger(Number(i.qty)) || Number(i.qty) < 1))
    throw Error('Check item descriptions, quantities, and prices');

  const subtotal = usedItems.reduce((s, i) => s + Number(i.qty) * Number(i.price), 0);

  const disc = Number(discount);

  if (!Number.isFinite(subtotal) || !Number.isFinite(disc) || disc < 0 || disc > subtotal)
    throw Error('Invalid amount or discount');
  // A regenerated receipt for an existing order retains its assigned OR number.

  const existing = order ? db.receipts.find(r => r.orderId === order.id) : null;

  const receipt = existing || { id: nextId(db.receipts), orNumber: order?.orNumber || nextOR(), orderId: order?.id || null, createdAt: new Date().toISOString() };

  Object.assign(receipt, { paymentMethod, otherPayment: paymentMethod === 'Others' ? String(otherPayment || '') : null, items: usedItems, subtotal, discount: disc, total: subtotal - disc, customerName: order ? db.customers.find(c => c.id === order.customerId)?.name : customerName, customerAddress: order ? db.customers.find(c => c.id === order.customerId)?.address || '' : customerAddress, customerContact: order ? db.customers.find(c => c.id === order.customerId)?.phone || '' : customerContact, receiptDate: order?.purchaseDate || receiptDate || receipt.createdAt });

  if (!existing)
    db.receipts.push(receipt);

  save();

  res.status(existing ? 200 : 201).json(receipt);
}));
