function validatedOrderItems(input) {

  const source = Array.isArray(input.items) ? input.items : [{ productId: input.productId, quantity: input.quantity }];

  if (!source.length || source.length > 200)
    throw Error('Add between 1 and 200 products to an order');

  const byId = new Map();

  for (const raw of source) {

    const id = Number(raw.productId), quantity = Number(raw.quantity), product = db.products.find(p => p.id === id);

    if (!product || !Number.isSafeInteger(quantity) || quantity < 1)
      throw Error('Select valid products and whole-number quantities');

    byId.set(id, (byId.get(id) || 0) + quantity);

  }

  return [...byId].map(([productId, quantity], index) => {

    const product = db.products.find(p => p.id === productId);
    return { id: index + 1, productId, quantity, unitPrice: Number(product.price) || 0 };
  });
}
function ensurePremiumStock(oldItems, newItems) {

  const previous = new Map();

  for (const i of oldItems) {

    const p = db.products.find(p => p.id === i.productId);

    if (p?.category === 'Premium Accounts')
      previous.set(p.id, (previous.get(p.id) || 0) + i.quantity);

  }

  for (const i of newItems) {

    const p = db.products.find(p => p.id === i.productId);

    if (p?.category === 'Premium Accounts') {

      const old = previous.get(p.id) || 0;

      if (i.quantity - old > Number(p.stock || 0))
        throw Error(`Not enough remaining stock for ${p.name}. Update Premium Inventory.`);

    }

  }

  for (const [id, qty] of previous) {

    const p = db.products.find(p => p.id === id);

    p.stock = Number(p.stock || 0) + qty;

  }

  for (const i of newItems) {

    const p = db.products.find(p => p.id === i.productId);

    if (p?.category === 'Premium Accounts')
      p.stock -= i.quantity;

  }
}
